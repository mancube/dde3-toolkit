#!/usr/bin/env python3
"""Generate src/live.rs — the DDE3 live-data / value-logger variable table.

The variables are the ADF (Analog/ Digital Function) entries that the DDE3
EDC15 M47 ECU actually exposes for live data / logging. They are read from
``tool32_edc15m_export.csv``, the tool32 ADF export of ``10DDE30.prg`` —
i.e. the loggable entries the ECU reports, not a hand-curated list copied
from another toolkit.

Per row we take:
    id       last two bytes of the TELEGRAM (the ADF id sent in
             ``12 05 0B 10 <id_hi> <id_lo>``) — the ADR column is unreliable
             (e.g. pump temp has ADR 0x0E10 but the frame id is 0x0E11).
    name     LNAME - ENG (the exported English display name)
    unit     MEAS
    factor   FACT_A   (physical = raw * FACT_A + FACT_B)
    offset   FACT_B
    group    derived from the ADF NAME prefix
    default_on  a fixed small set of commonly-wanted values

Rows sharing an ADF id are de-duplicated (the first occurrence wins); a
duplicate id is unreachable in the app, which indexes the table by id.

Usage:
    python3 tools/gen_live_rs.py [path/to/tool32_edc15m_export.csv]
"""
import os
import sys
import csv

DEFAULT_CSV = '/home/ilija/Desktop/logger/tool32_edc15m_export.csv'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'live.rs')

# ADF NAME prefix -> friendly GUI group label. Unknown prefixes fall back to
# the upper-cased prefix so every variable still lands in a named bucket.
GROUPS = {
    'mrm': 'Injection',
    'pkm': 'Engine',
    'dzm': 'Engine',
    'klm': 'Engine',
    'ehm': 'Actuators',
    'ldm': 'Air & boost',
    'arm': 'Air & boost',
    'ldo': 'Air & boost',
    'anm': 'Sensors',
    'ano': 'Sensors',
    'fgm': 'Speed',
    'sbm': 'Timing',
    'sbo': 'Timing',
    'fnm': 'Fuel',
    'dim': 'Digital',
    'fbm': 'Counters',
    'mro': 'Misc',
    'kho': 'Misc',
    'aro': 'Misc',
    'com': 'Misc',
}

# Values shown on by default (engine speed, coolant, battery, pedal, boost).
DEFAULT_ON = {0x0F10, 0x0F00, 0x0F65, 0x0F83, 0x0F40}


def fmt_num(s):
    # emit a Rust f64 literal: add .0 to bare integers
    s = s.strip()
    if s and ('.' not in s) and ('e' not in s.lower()):
        return s + '.0'
    return s


def main():
    csv_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CSV
    rows = list(csv.DictReader(open(csv_path, newline='', encoding='utf-8')))

    seen = set()
    entries = []
    skipped_dups = []
    for r in rows:
        tel = r['TELEGRAM'].strip()
        if len(tel) < 4:
            continue
        id_hex = tel[-4:]
        id_ = int(id_hex, 16)
        if id_ in seen:
            skipped_dups.append((id_hex, r['NAME'], r['LNAME - ENG'].strip()))
            continue
        seen.add(id_)
        pref = r['NAME'].strip()[:3]
        group = GROUPS.get(pref, pref.upper())
        entries.append({
            'name': r['LNAME - ENG'].strip(),
            'unit': r['MEAS'].strip() or '-',
            'id': id_,
            'factor': fmt_num(r['FACT_A']),
            'offset': fmt_num(r['FACT_B']),
            'group': group,
            'default_on': id_ in DEFAULT_ON,
        })

    # sort within a stable, sensible order: by group then id
    order = {g: i for i, g in enumerate(GROUPS.values())}
    entries.sort(key=lambda e: (order.get(e['group'], 999), e['id']))

    lines = []
    lines.append('//! DDE3 live-data / value-logger variable table (ADF entries).')
    lines.append('//!')
    lines.append('//! Generated by `tools/gen_live_rs.py` from the tool32 ADF export of')
    lines.append('//! 10DDE30.prg (tool32_edc15m_export.csv) — do not edit by hand.')
    lines.append('//!')
    lines.append('//! These are the measurement values the ECU actually exposes for live')
    lines.append('//! data and value logging. Telegram: `12 05 0B 10 <id_hi> <id_lo>`.')
    lines.append('//! Scaling: physical = raw * factor + offset.')
    lines.append('')
    lines.append('#[derive(Clone)]')
    lines.append('pub struct LiveVar {')
    lines.append('    pub name: &\'static str,')
    lines.append('    pub unit: &\'static str,')
    lines.append('    pub id: u16,')
    lines.append('    pub factor: f64,')
    lines.append('    pub offset: f64,')
    lines.append('    pub group: &\'static str,')
    lines.append('    pub default_on: bool,')
    lines.append('}')
    lines.append('')
    lines.append(f'// {len(entries)} ADF variables.')
    lines.append('pub const LIVE_VARS: &[LiveVar] = &[')
    last_group = None
    for e in entries:
        if e['group'] != last_group:
            last_group = e['group']
            lines.append(f'    // {e["group"]}')
        on = 'true' if e['default_on'] else 'false'
        line = (
            f'    LiveVar {{ name: "{e["name"]}", '
            f'unit: "{e["unit"]}", '
            f'id: 0x{e["id"]:04X}, '
            f'factor: {e["factor"]}, '
            f'offset: {e["offset"]}, '
            f'group: "{e["group"]}", '
            f'default_on: {on} }},'
        )
        lines.append(line)
    lines.append('];')
    lines.append('')

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print(f'wrote {OUT}: {len(entries)} variables')
    for h, n, e in skipped_dups:
        print(f'  skipped duplicate ADF id 0x{h} ({n}: {e})')


if __name__ == '__main__':
    main()
