#!/usr/bin/env python3
"""Generate src/dtc.rs from the DDE3 WinKFP data set DDE30DS0.prg.

The EDIABAS .prg body (XOR 0xF7) contains four NUL-separated string tables
used by the fault-memory jobs (FS_QUICK_LESEN / FS_LESEN / FS_SHADOW_LESEN):

    ORT         @ body 0x6b725   ORT.ORTTEXT.UW_1.UW_2          (fault location)
    FArtMatrix  @ body 0x6bf7a   ORT.A1_0.A1_1...A8_0.A8_1      (slot map)
    FArtTexte   @ body 0x6cf69   ARTNR.ARTTEXT                 (fault type text)
    FUmweltTexte@ body 0x6df52   UWNR.UWTEXT.UW_EINH.UWF_A.UWF_B (freeze values)

Usage:
    python3 tools/gen_dtc_rs.py [path/to/DDE30DS0.prg]
"""
import sys
import os

DEFAULT_PRG = '/home/ilija/Desktop/logger/DDE30DS0.prg'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'dtc.rs')

ORT_OFF = 0x6b725
MATRIX_OFF = 0x6bf7a
FART_OFF = 0x6cf69
UMWELT_OFF = 0x6df52
UMWELT_ROWS_OFF = 0x6df72
UMWELT_END_MARKER = b'SH_FE\x00'  # next table in the data area

HEX16 = lambda s: s.startswith('0x') and len(s) == 4 and all(c in '0123456789ABCDEFabcdefXY' for c in s[2:])


def load_body(path):
    raw = open(path, 'rb').read()
    return bytes(b ^ 0xF7 for b in raw[0xA0:])


def fields(body, start, stop):
    out, i = [], start
    while i < stop:
        j = body.find(b'\x00', i, stop)
        if j == -1:
            break
        out.append(body[i:j].decode('latin1', 'replace'))
        i = j + 1
    return out


def parse_ort(body):
    f = fields(body, ORT_OFF, MATRIX_OFF)
    assert f[:4] == ['ORT', 'ORTTEXT', 'UW_1', 'UW_2'], f[:4]
    rows = []
    for i in range(4, len(f), 4):
        r = f[i:i + 4]
        code = 0xFF if r[0] == '0xXY' else int(r[0], 16)
        text = r[1] if len(r) > 1 else '--'
        u1 = int(r[2], 16) if len(r) > 2 and HEX16(r[2]) else 0
        u2 = int(r[3], 16) if len(r) > 3 and HEX16(r[3]) else 0
        rows.append((code, text, u1, u2))
    return rows


def parse_matrix(body):
    f = fields(body, MATRIX_OFF, FART_OFF)
    assert f[0] == 'ORT' and f[1] == 'A1_0' and f[16] == 'A8_1', f[:3]
    rows = []
    for i in range(17, len(f), 17):
        r = f[i:i + 17]
        code = 0xFF if r[0] == '0xXY' else int(r[0], 16)
        vals = [int(x, 16) for x in r[1:17]]
        rows.append((code, vals))
    return rows


def parse_fart(body):
    f = fields(body, FART_OFF, UMWELT_OFF)
    assert f[:2] == ['ARTNR', 'ARTTEXT'], f[:2]
    rows = []
    for i in range(2, len(f), 2):
        r = f[i:i + 2]
        code = int(r[0], 16)
        rows.append((code, r[1]))
    return rows


def parse_umwelt(body):
    f = fields(body, UMWELT_ROWS_OFF, UMWELT_OFF + 5000)
    rows = []
    for i in range(0, len(f), 5):
        r = f[i:i + 5]
        if not r or not HEX16(r[0]) and r[0] != '0xXY':
            break
        code = 0xFF if r[0] == '0xXY' else int(r[0], 16)
        try:
            a, b = float(r[3]), float(r[4])
        except ValueError:
            break
        rows.append((code, r[1], r[2], a, b))
    return rows


def rs_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    prg = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PRG
    body = load_body(prg)
    ort = parse_ort(body)
    matrix = parse_matrix(body)
    fart = parse_fart(body)
    umwelt = parse_umwelt(body)
    print(f'ORT: {len(ort)} rows, MATRIX: {len(matrix)} rows, FART: {len(fart)} rows, UMWELT: {len(umwelt)} rows')

    def fmt(rows, cols):
        return ',\n'.join('    ' + cols(r) for r in rows)

    lines = []
    lines.append('//! DDE3 fault-memory (DTC) text tables and helpers.')
    lines.append('//!')
    lines.append(f'//! Generated by `tools/gen_dtc_rs.py` from `{os.path.basename(prg)}` —')
    lines.append('//! do not edit by hand. EDIABAS body (XOR 0xF7), NUL-separated tables:')
    lines.append('//!   ORT table        @ body 0x6b725   ORT.ORTTEXT.UW_1.UW_2')
    lines.append('//!   FArtMatrix       @ body 0x6bf7a   ORT.A1_0.A1_1 ... A8_0.A8_1')
    lines.append('//!   FArtTexte        @ body 0x6cf69   ARTNR.ARTTEXT')
    lines.append('//!   FUmweltTexte     @ body 0x6df52   UWNR.UWTEXT.UW_EINH.UWF_A.UWF_B')
    lines.append('//!')
    lines.append('//! Fault-memory protocol (from the FS_* jobs in the same file):')
    lines.append('//!   start/count  `12 05 14 01`  -> `92 05 A0 <anz>`')
    lines.append('//!   entry n      `12 05 04 <n>` -> `92 05 A0 <ort> <art> <uw1:2> <uw2:2>`')
    lines.append('//!   clear        `12 04 05`     -> `92 04 A0`')
    lines.append('//!')
    lines.append('//! Freeze values: `value = A * raw + B` (raw is big-endian u16).')
    lines.append('')
    lines.append(f'/// Fault location: `(code, German text, UW_1 id, UW_2 id)`. {len(ort)} rows.')
    lines.append('pub const ORT: &[(u8, &str, u8, u8)] = &[')
    lines.append(fmt(ort, lambda r: f'({r[0]:#04x}, {rs_str(r[1])}, {r[2]:#04x}, {r[3]:#04x})'))
    lines.append('];')
    lines.append('')
    lines.append(f'/// Fault type (ARTNR): `(code, German text)`. {len(fart)} rows.')
    lines.append('pub const FART: &[(u8, &str)] = &[')
    lines.append(fmt(fart, lambda r: f'({r[0]:#04x}, {rs_str(r[1])})'))
    lines.append('];')
    lines.append('')
    lines.append(f'/// Freeze-frame measurements: `(id, name, unit, A, B)`. {len(umwelt)} rows.')
    lines.append('pub const UMWELT: &[(u8, &str, &str, f64, f64)] = &[')
    lines.append(fmt(umwelt, lambda r: f'({r[0]:#04x}, {rs_str(r[1])}, {rs_str(r[2])}, {r[3]!r}, {r[4]!r})'))
    lines.append('];')
    lines.append('')
    lines.append(f'/// FArtMatrix: ORT -> 16 ART slot codes `(A1_0, A1_1, ..., A8_1)`. {len(matrix)} rows.')
    lines.append('#[allow(dead_code)]')
    lines.append('pub const MATRIX: &[(u8, [u8; 16])] = &[')
    lines.append(fmt(matrix, lambda r: f'({r[0]:#04x}, [{", ".join(f"{v:#04x}" for v in r[1])}])'))
    lines.append('];')
    lines.append('')
    lines.append('/// Battery-voltage measurement id (UW 0x08, Batteriespannung [V]).')
    lines.append('#[allow(dead_code)]')
    lines.append('pub const UW_BATTERY: u8 = 0x08;')
    lines.append('')
    lines.append('/// One environment (freeze-frame) measurement.')
    lines.append('#[derive(Clone, Copy, Debug)]')
    lines.append('pub struct Uw {')
    lines.append('    pub id: u8,')
    lines.append('    pub name: &\'static str,')
    lines.append('    pub unit: &\'static str,')
    lines.append('    pub a: f64,')
    lines.append('    pub b: f64,')
    lines.append('}')
    lines.append('')
    lines.append('/// German text for a fault-location code; falls back to `unbekannter Fehlerort`.')
    lines.append('pub fn ort_text(code: u8) -> &\'static str {')
    lines.append('    ORT.iter().find(|(c, _, _, _)| *c == code).map(|(_, t, _, _)| *t).unwrap_or("unbekannter Fehlerort")')
    lines.append('}');
    lines.append('')
    lines.append('/// German text for a fault-type code; falls back to `unbekannte Fehlerart`.')
    lines.append('pub fn fart_text(code: u8) -> &\'static str {')
    lines.append('    FART.iter().find(|(c, _)| *c == code).map(|(_, t)| *t).unwrap_or("unbekannte Fehlerart")')
    lines.append('}');
    lines.append('')
    lines.append('/// The two freeze-frame measurement ids used for a fault location.')
    lines.append('pub fn ort_uw_ids(code: u8) -> (u8, u8) {')
    lines.append('    ORT.iter().find(|(c, _, _, _)| *c == code).map(|(_, _, u1, u2)| (*u1, *u2)).unwrap_or((0, 0))')
    lines.append('}');
    lines.append('')
    lines.append('/// Environment table entry for a measurement id.')
    lines.append('pub fn uw_info(id: u8) -> Option<Uw> {')
    lines.append('    UMWELT.iter().find(|(c, _, _, _, _)| *c == id).map(|(c, n, u, a, b)| Uw { id: *c, name: *n, unit: *u, a: *a, b: *b })')
    lines.append('}');
    lines.append('')
    lines.append('/// Scale a raw freeze value: `a * raw + b` (or 0.0 if the id is unknown).')
    lines.append('pub fn uw_value(id: u8, raw: u16) -> f64 {')
    lines.append('    match uw_info(id) { Some(u) => u.a * (raw as f64) + u.b, None => 0.0 }')
    lines.append('}');
    lines.append('')
    lines.append('/// ART slot codes for a fault location (FArtMatrix row), if present.')
    lines.append('#[allow(dead_code)]')
    lines.append('pub fn matrix_row(ort: u8) -> Option<&\'static [u8; 16]> {')
    lines.append('    MATRIX.iter().find(|(c, _)| *c == ort).map(|(_, v)| v)')
    lines.append('}');
    lines.append('')
    lines.append('#[cfg(test)]')
    lines.append('mod tests {')
    lines.append('    use super::*;')
    lines.append('    #[test]')
    lines.append('    fn tables_are_sorted_sparse() {')
    lines.append('        assert!(ORT.windows(2).all(|w| w[0].0 < w[1].0));')
    lines.append('        assert!(FART.windows(2).all(|w| w[0].0 < w[1].0));')
    lines.append('        assert!(UMWELT.windows(2).all(|w| w[0].0 < w[1].0));')
    lines.append('    }')
    lines.append('    #[test]')
    lines.append('    fn known_entries() {')
    lines.append('        assert_eq!(ort_text(0x05), "Nadelbewegungsfuehler");')
    lines.append('        assert_eq!(fart_text(0x01), "Signal Kurzschluss nach B+");')
    lines.append('        let (u1, u2) = ort_uw_ids(0x05);')
    lines.append('        assert_eq!((u1, u2), (0x02, 0x07));')
    lines.append('        let uw = uw_info(0x08).expect("battery voltage entry");')
    lines.append('        assert_eq!(uw.name, "Batteriespannung");')
    lines.append('        assert!((uw_value(0x08, 148.0 as u16) - 14.78).abs() < 0.05);')
    lines.append('        assert!(matrix_row(0x00).is_some());')
    lines.append('        assert_eq!(ort_text(0x02), "unbekannter Fehlerort");')
    lines.append('        assert_eq!(fart_text(0x91), "unbekannte Fehlerart");')
    lines.append('    }')
    lines.append('}');
    lines.append('')

    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {OUT} ({os.path.getsize(OUT)} bytes)')


if __name__ == '__main__':
    main()
